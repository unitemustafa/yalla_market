"""Keep iOS Associated Domains aligned with the build's API_BASE_URL."""

import json
import os
from pathlib import Path
import re
import sys
from urllib.parse import urlsplit


def shared_link_host(api_base_url):
    parsed = urlsplit(api_base_url.strip())
    if (
        parsed.scheme != "https"
        or not parsed.hostname
        or not re.fullmatch(r"[a-zA-Z0-9.-]+", parsed.hostname)
        or parsed.username
        or parsed.password
        or parsed.port not in (None, 443)
        or parsed.path not in ("", "/")
        or parsed.query
        or parsed.fragment
    ):
        raise ValueError("API_BASE_URL must be an HTTPS root URL.")
    return parsed.hostname.lower()


def main():
    if len(sys.argv) > 2:
        raise ValueError("Pass one environment JSON file, or set API_BASE_URL.")
    api_url = (
        json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))["API_BASE_URL"]
        if len(sys.argv) == 2
        else os.environ.get("API_BASE_URL", "")
    )
    host = shared_link_host(api_url)
    target = Path(__file__).resolve().parents[1] / "ios/Flutter/SharedLinks.xcconfig"
    target.write_text(
        "// Generated by tool/configure_shared_links.py; contains only the public host.\n"
        f"SHARED_LINK_HOST = {host}\n",
        encoding="utf-8",
    )
    print("iOS shared-link domain configured.")


if __name__ == "__main__":
    main()
